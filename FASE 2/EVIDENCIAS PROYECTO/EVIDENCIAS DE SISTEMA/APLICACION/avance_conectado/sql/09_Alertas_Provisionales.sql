BEGIN;
SET LOCAL search_path=rutaalerta,public,extensions;

ALTER TABLE organizacion ADD COLUMN IF NOT EXISTS alertas_provisionales_habilitadas boolean NOT NULL DEFAULT false;
ALTER TABLE vinculo_vehiculo ADD COLUMN IF NOT EXISTS id_organizacion_revision bigint REFERENCES organizacion;
ALTER TABLE vinculo_vehiculo ADD COLUMN IF NOT EXISTS referencia_revision varchar(80);
ALTER TABLE vinculo_vehiculo ADD COLUMN IF NOT EXISTS vence_revision_en timestamptz;
ALTER TABLE caso ADD COLUMN IF NOT EXISTS sustraccion_declarada_en timestamptz;
ALTER TABLE caso ADD COLUMN IF NOT EXISTS revision_alerta integer NOT NULL DEFAULT 0;
ALTER TABLE solicitud_colaboracion ADD COLUMN IF NOT EXISTS modo_alerta text NOT NULL DEFAULT 'revisada'
 CHECK (modo_alerta IN ('revisada','provisional','encargo_comprobado'));
ALTER TABLE solicitud_colaboracion ADD COLUMN IF NOT EXISTS id_vinculo_verificado bigint REFERENCES vinculo_vehiculo;
ALTER TABLE solicitud_colaboracion ADD COLUMN IF NOT EXISTS suspendida_en timestamptz;

CREATE TABLE IF NOT EXISTS consulta_encargo (
 id_consulta_encargo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_caso bigint NOT NULL REFERENCES caso,
 id_operador bigint NOT NULL REFERENCES usuario,
 resultado text NOT NULL CHECK (resultado IN ('encontrado','sin_resultado','no_disponible')),
 fuente text NOT NULL CHECK (fuente IN ('Auto Seguro','Simulador RutaAlerta')),
 consultada_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 referencia varchar(80),
 observacion varchar(500) NOT NULL,
 simulada boolean NOT NULL DEFAULT false,
 id_evidencia bigint,
 FOREIGN KEY (id_evidencia,id_caso) REFERENCES evidencia(id_evidencia,id_caso),
 CHECK ((fuente='Simulador RutaAlerta')=simulada)
);
CREATE INDEX IF NOT EXISTS ix_consulta_encargo_caso ON consulta_encargo(id_caso,id_consulta_encargo DESC);
CREATE INDEX IF NOT EXISTS ix_caso_alertas_vehiculo ON caso(id_vehiculo,entorno) WHERE estado<>'cerrado';
DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='ra_api') THEN
  GRANT SELECT,INSERT ON consulta_encargo TO ra_api;
  GRANT USAGE,SELECT ON SEQUENCE consulta_encargo_id_consulta_encargo_seq TO ra_api;
 END IF;
END $$;
COMMIT;
